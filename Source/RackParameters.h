using Values = std::array<float, Count>;
inline Values defaults() {
  Values v{};
  for (size_t i = 0; i < v.size(); ++i)
    v[i] = specs()[i].def;
  return v;
}
inline juce::AudioProcessorValueTreeState::ParameterLayout layout() {
  juce::AudioProcessorValueTreeState::ParameterLayout p;
  for (size_t i = 0; i < Count; ++i) {
    const auto &s = specs()[i];
    juce::ParameterID id{s.id, 1};
    if (i == VoiceType)
      p.add(std::make_unique<juce::AudioParameterChoice>(
          id, s.name,
          juce::StringArray{"PRINCIPAL", "DOBLES", "REFUERZOS", "ADLIBS",
                            "ARMONIAS", "BUS VOCAL"},
          0));
    else if (i == DelayNote)
      p.add(std::make_unique<juce::AudioParameterChoice>(
          id, s.name,
          juce::StringArray{"1/16", "1/8", "1/8 D", "1/4", "1/4 D", "1/2"}, 1));
    else if (i == ModType)
      p.add(std::make_unique<juce::AudioParameterChoice>(
          id, s.name, juce::StringArray{"Chorus", "Flanger", "Vibrato"}, 0));
    else if (i == PitchKey)
      p.add(std::make_unique<juce::AudioParameterChoice>(
          id, s.name,
          juce::StringArray{"Auto", "C", "C#", "D", "D#", "E", "F", "F#", "G",
                            "G#", "A", "A#", "B"},
          0));
    else if (i == PitchScale)
      p.add(std::make_unique<juce::AudioParameterChoice>(
          id, s.name, juce::StringArray{"Auto", "Chromatic", "Major", "Minor"},
          0));
    else if (i == EngineMode || i == PreampStyle || i == PitchStyle ||
             i == HarmonyPattern || i == ReverbStyle || i == DelayStyle ||
             i == SatStyle) {
      juce::StringArray choices;
      if (i == EngineMode)
        choices = {"Monitor 0 ms", "Studio 8x", "Linear FIR 8x"};
      if (i == PreampStyle)
        choices = {"Iron 73", "Punch 512",  "Edge 4K",
                   "Air 737", "Velvet Box", "Dirty TG"};
      if (i == PitchStyle)
        choices = {"Natural", "Robot"};
      if (i == HarmonyPattern)
        choices = {"Octaves", "Fifths", "Choir", "Angelic"};
      if (i == ReverbStyle)
        choices = {"Chamber", "Hall", "Plate"};
      if (i == DelayStyle)
        choices = {"Slap", "Throw", "Ping-Pong", "Tape Ducking",
                   "Ping-Pong + Verb"};
      if (i == SatStyle)
        choices = {"Tube", "Tape", "Transistor", "Transformer", "Crush"};
      p.add(std::make_unique<juce::AudioParameterChoice>(id, s.name, choices,
                                                         int(s.def)));
    } else if (s.toggle)
      p.add(
          std::make_unique<juce::AudioParameterBool>(id, s.name, s.def > .5f));
    else
      p.add(std::make_unique<juce::AudioParameterFloat>(
          id, s.name,
          juce::NormalisableRange<float>(s.min, s.max, s.step, s.skew), s.def));
  }
  return p;
}
